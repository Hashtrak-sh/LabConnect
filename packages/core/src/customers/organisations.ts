import { type CustomerSegment, type OrgStatus, type Prisma, uuidv7 } from '@labconnect/database';
import { auditMeta, type RequestMeta } from '../identity/errors.js';
import type { AuditService } from '../platform/audit.js';
import type { Clock } from '../platform/clock.js';

/** A postal address as the contract spells it (`PostalAddress`). */
export interface PostalAddressInput {
  line1: string;
  line2: string | null;
  city: string;
  district: string | null;
  stateCode: string;
  pincode: string;
}

export interface CustomerOrganisationInput {
  customerSegment: CustomerSegment;
  legalName: string;
  displayName: string;
  gstin?: string;
  registeredAddress?: PostalAddressInput;
}

/** A customer organisation as the API returns it (`CustomerOrganisation`). */
export interface CustomerOrganisationView {
  id: string;
  customerSegment: CustomerSegment;
  legalName: string;
  displayName: string;
  gstin: string | null;
  registeredAddress: PostalAddressInput | null;
  status: OrgStatus;
  createdAt: Date;
  lockVersion: number;
}

export type CreateCustomerOrganisationResult =
  | { ok: true; organisation: CustomerOrganisationView; membershipId: string }
  | { ok: false; reason: 'USER_NOT_ACTIVE' | 'USER_IS_PLATFORM_STAFF' | 'GSTIN_TAKEN' };

export interface CustomerOrganisationDeps {
  clock: Clock;
  audit: AuditService;
}

/** The stored form of an address (`organisation.registered_address`, SCHEMA_SPECIFICATION §2.1). */
function storedAddress(address: PostalAddressInput): Prisma.InputJsonObject {
  return {
    line1: address.line1,
    line2: address.line2,
    city: address.city,
    district: address.district,
    state_code: address.stateCode,
    pincode: address.pincode,
  };
}

/** Reads a stored address back; anything unexpected reads as no address. */
export function addressFromStored(value: Prisma.JsonValue | null): PostalAddressInput | null {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return null;
  const text = (key: string): string | null => {
    const field = value[key];
    return typeof field === 'string' ? field : null;
  };
  const line1 = text('line1');
  const city = text('city');
  const stateCode = text('state_code');
  const pincode = text('pincode');
  if (line1 === null || city === null || stateCode === null || pincode === null) return null;
  return { line1, line2: text('line2'), city, district: text('district'), stateCode, pincode };
}

/**
 * Customer self-sign-up (FR-ONB-01, `createCustomerOrganisation`). Creates the organisation
 * (`CUSTOMER`, claim status `NOT_APPLICABLE`), its private row and its settings, and makes the
 * caller its first `CUSTOMER_ADMIN` with an active membership. Audited as `organisation.create`
 * and `role.change`.
 *
 * Run it in the context of the *new* organisation (`TenantScope.runForNewOrganisation`), with
 * `organisationId` generated by the server: the policies then let the transaction write that
 * organisation's rows and nobody else's. It refuses, and writes nothing, when the user is not
 * `ACTIVE`, is platform staff (RR-5) or when another customer organisation already uses the
 * GSTIN. The unique index on (org_type, gstin) backs the last check against a race; the caller
 * maps that violation to `GSTIN_TAKEN` too.
 */
export async function createCustomerOrganisation(
  tx: Prisma.TransactionClient,
  deps: CustomerOrganisationDeps,
  input: {
    userId: string;
    organisationId: string;
    organisation: CustomerOrganisationInput;
    meta: RequestMeta;
  },
): Promise<CreateCustomerOrganisationResult> {
  const now = deps.clock.now();
  const at = now.getTime();
  const user = await tx.appUser.findUnique({
    where: { id: input.userId },
    select: { status: true, isPlatformStaff: true },
  });
  if (user?.status !== 'ACTIVE') return { ok: false, reason: 'USER_NOT_ACTIVE' };
  if (user.isPlatformStaff) return { ok: false, reason: 'USER_IS_PLATFORM_STAFF' };

  const { organisation } = input;
  if (organisation.gstin !== undefined) {
    const taken = await tx.organisation.findFirst({
      where: { orgType: 'CUSTOMER', gstin: organisation.gstin },
      select: { id: true },
    });
    if (taken !== null) return { ok: false, reason: 'GSTIN_TAKEN' };
  }

  const created = await tx.organisation.create({
    data: {
      id: input.organisationId,
      orgType: 'CUSTOMER',
      customerSegment: organisation.customerSegment,
      legalName: organisation.legalName,
      displayName: organisation.displayName,
      gstin: organisation.gstin ?? null,
      ...(organisation.registeredAddress !== undefined && {
        registeredAddress: storedAddress(organisation.registeredAddress),
      }),
      claimStatus: 'NOT_APPLICABLE',
      status: 'ACTIVE',
      createdAt: now,
      updatedAt: now,
      createdByUserId: input.userId,
    },
  });
  await tx.organisationPrivate.create({
    data: {
      id: uuidv7(at),
      organisationId: created.id,
      createdAt: now,
      updatedAt: now,
      createdByUserId: input.userId,
    },
  });
  await tx.customerSettings.create({
    data: {
      id: uuidv7(at),
      organisationId: created.id,
      createdAt: now,
      updatedAt: now,
      createdByUserId: input.userId,
    },
  });

  const membershipId = uuidv7(at);
  await tx.membership.create({
    data: {
      id: membershipId,
      userId: input.userId,
      organisationId: created.id,
      status: 'ACTIVE',
      activatedAt: now,
      createdAt: now,
      updatedAt: now,
      createdByUserId: input.userId,
    },
  });
  await tx.membershipRole.create({
    data: {
      id: uuidv7(at),
      membershipId,
      role: 'CUSTOMER_ADMIN',
      grantedByUserId: input.userId,
      createdAt: now,
      updatedAt: now,
      createdByUserId: input.userId,
    },
  });

  const view = toView(created);
  const actor = {
    userId: input.userId,
    membershipId,
    role: 'CUSTOMER_ADMIN' as const,
    orgId: created.id,
  };
  const meta = auditMeta(input.meta);
  await deps.audit.record(tx, {
    actor,
    action: 'organisation.create',
    entityType: 'organisation',
    entityId: created.id,
    after: {
      orgType: 'CUSTOMER',
      customerSegment: view.customerSegment,
      legalName: view.legalName,
      displayName: view.displayName,
      gstin: view.gstin,
    },
    ...meta,
  });
  await deps.audit.record(tx, {
    actor,
    action: 'role.change',
    entityType: 'membership',
    entityId: membershipId,
    after: { role: 'CUSTOMER_ADMIN', granted: true, reason: 'self sign-up' },
    ...meta,
  });
  return { ok: true, organisation: view, membershipId };
}

function toView(row: {
  id: string;
  customerSegment: CustomerSegment | null;
  legalName: string;
  displayName: string;
  gstin: string | null;
  registeredAddress: Prisma.JsonValue | null;
  status: OrgStatus;
  createdAt: Date;
  lockVersion: number;
}): CustomerOrganisationView {
  return {
    id: row.id,
    // A customer organisation always has a segment (the database check on org_type CUSTOMER).
    customerSegment: row.customerSegment ?? 'INDIVIDUAL',
    legalName: row.legalName,
    displayName: row.displayName,
    gstin: row.gstin,
    registeredAddress: addressFromStored(row.registeredAddress),
    status: row.status,
    createdAt: row.createdAt,
    lockVersion: row.lockVersion,
  };
}
