import type { FilePurpose } from '@labconnect/database';
import { FilesError } from './errors.js';

const MB = 1024 * 1024;

export const CONTENT_TYPES = {
  pdf: 'application/pdf',
  jpeg: 'image/jpeg',
  png: 'image/png',
  heic: 'image/heic',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  csv: 'text/csv',
} as const;

export type AllowedContentType = (typeof CONTENT_TYPES)[keyof typeof CONTENT_TYPES];

export interface PurposeRule {
  /** Declared content types a client may upload for this purpose. */
  contentTypes: readonly AllowedContentType[];
  /** Largest single file, in bytes. */
  maxBytes: number;
}

/**
 * The upload limits of every client-uploadable purpose: the table of FILES_AND_REPORTS.md
 * section 1, in bytes, and the same numbers as the per-purpose request schemas of
 * `packages/api-contract/openapi/components/schemas/files.yaml`. The one place that knows them.
 *
 * Two limits of that table are not per-file limits and belong to the owning module: at most
 * 10 receipt photos per receipt, and 25 MB in total for the attachments of one booking
 * (BR-021). Here `BOOKING_ATTACHMENT` is checked per file at 25 MB.
 *
 * `REPORT_STAMPED`, `FINANCIAL_DOCUMENT`, `LABEL_SHEET` and `CUSTODY_TRAIL` are generated by the
 * platform, never uploaded by a client, so they have no rule and `requestUpload` refuses them.
 */
export const UPLOAD_RULES: Partial<Record<FilePurpose, PurposeRule>> = {
  REPORT_ORIGINAL: { contentTypes: [CONTENT_TYPES.pdf], maxBytes: 20 * MB },
  RECEIPT_PHOTO: {
    contentTypes: [CONTENT_TYPES.jpeg, CONTENT_TYPES.png, CONTENT_TYPES.heic],
    maxBytes: 10 * MB,
  },
  BOOKING_ATTACHMENT: {
    contentTypes: [
      CONTENT_TYPES.pdf,
      CONTENT_TYPES.jpeg,
      CONTENT_TYPES.png,
      CONTENT_TYPES.xlsx,
      CONTENT_TYPES.docx,
    ],
    maxBytes: 25 * MB,
  },
  KYC_DOCUMENT: {
    contentTypes: [CONTENT_TYPES.pdf, CONTENT_TYPES.jpeg, CONTENT_TYPES.png],
    maxBytes: 10 * MB,
  },
  DISPUTE_EVIDENCE: {
    contentTypes: [CONTENT_TYPES.pdf, CONTENT_TYPES.jpeg, CONTENT_TYPES.png],
    maxBytes: 10 * MB,
  },
  IMPORT_SOURCE: { contentTypes: [CONTENT_TYPES.csv, CONTENT_TYPES.xlsx], maxBytes: 50 * MB },
};

/**
 * Purposes whose files are Restricted data (SECURITY_AND_PRIVACY.md: "access logged"): every
 * download URL issued for them is audited.
 */
export const AUDITED_DOWNLOAD_PURPOSES: ReadonlySet<FilePurpose> = new Set<FilePurpose>([
  'REPORT_ORIGINAL',
  'REPORT_STAMPED',
  'KYC_DOCUMENT',
]);

export function ruleFor(purpose: FilePurpose): PurposeRule {
  const rule = UPLOAD_RULES[purpose];
  if (!rule) {
    throw new FilesError('VALIDATION_FAILED', {
      reason: 'PURPOSE_NOT_UPLOADABLE',
      detail: 'Files of this purpose cannot be uploaded.',
    });
  }
  return rule;
}

/**
 * Checks a declared type and size against the rule of the purpose. The content type is
 * compared exactly (no parameters such as `; charset=`), because the signed upload sends
 * exactly this value.
 */
export function assertUploadAllowed(
  purpose: FilePurpose,
  declaredContentType: string,
  declaredSizeBytes: number,
): PurposeRule {
  const rule = ruleFor(purpose);
  if (!(rule.contentTypes as readonly string[]).includes(declaredContentType)) {
    throw new FilesError('VALIDATION_FAILED', {
      reason: 'CONTENT_TYPE_NOT_ALLOWED',
      detail: 'This file type is not allowed for this upload.',
      meta: { allowedContentTypes: [...rule.contentTypes] },
    });
  }
  if (
    !Number.isSafeInteger(declaredSizeBytes) ||
    declaredSizeBytes < 1 ||
    declaredSizeBytes > rule.maxBytes
  ) {
    throw new FilesError('VALIDATION_FAILED', {
      reason: 'SIZE_LIMIT_EXCEEDED',
      detail: 'The file size is not allowed for this upload.',
      meta: { maxBytes: rule.maxBytes },
    });
  }
  return rule;
}
