export interface DemoGuide {
  searches: readonly DemoSearchTip[];
  bookableSites: { name: string; certificateNo: string }[];
  /** Listed labs that nobody has claimed, for the claim story. */
  claimLabs: { name: string; certificateNo: string }[];
  accounts: { role: string; email: string }[];
}

/** How many unclaimed labs the claim story names. */
const CLAIM_LAB_COUNT = 2;

export function demoGuide(domain = DEMO_EMAIL_DOMAIN): DemoGuide {
  const bookableSites = NAMED_LABS.filter((lab) => lab.onboarded).flatMap((lab) =>
    lab.sites.map((site, index) => ({
      name: siteNameOf(lab.name, site.city),
      certificateNo: certificateNoOf(lab.tag, index),
    })),
  );
  const claimLabs = NAMED_LABS.filter((lab) => !lab.onboarded)
    .slice(0, CLAIM_LAB_COUNT)
    .map((lab) => ({
      name: siteNameOf(lab.name, lab.sites[0]?.city ?? 'Delhi'),
      certificateNo: certificateNoOf(lab.tag),
    }));
  return { searches: DEMO_SEARCH_TIPS, bookableSites, claimLabs, accounts: demoAccounts(domain) };
}

export const DEMO_GUIDE_START = '<!-- demo-guide:start -->';
export const DEMO_GUIDE_END = '<!-- demo-guide:end -->';

const cell = (text: string): string => text.replaceAll('|', '\\|');

/** The markdown between the two markers of `infrastructure/README.md`, markers included. */
export function renderDemoGuide(domain = DEMO_EMAIL_DOMAIN): string {
  const guide = demoGuide(domain);
  const lines = [
    DEMO_GUIDE_START,
    '<!-- Generated by renderDemoGuide() in packages/database/src/seed/demo-guide.ts; a test fails if this block differs from its output. -->',
    '',
    '| Type in the search box | What it shows |',
    '|---|---|',
    ...guide.searches.map((tip) => `| \`${tip.term}\` | ${cell(tip.shows)} |`),
    '',
    'The four bookable sites (prices, slots, a booking in every state):',
    '',
    '| Site | Certificate |',
    '|---|---|',
    ...guide.bookableSites.map((site) => `| ${site.name} | \`${site.certificateNo}\` |`),
    '',
    'Two unclaimed labs for the claim story (the lab owner accounts below hold no role, so a claim can be approved):',
    '',
    '| Lab | Certificate |',
    '|---|---|',
    ...guide.claimLabs.map((labEntry) => `| ${labEntry.name} | \`${labEntry.certificateNo}\` |`),
    '',
    `Demo accounts (all in \`${domain}\`; the sign-in code is the one set for the environment):`,
    '',
    '| Role | Address |',
    '|---|---|',
    ...guide.accounts.map((account) => `| ${account.role} | \`${account.email}\` |`),
    DEMO_GUIDE_END,
  ];
  return lines.join('\n');
}
